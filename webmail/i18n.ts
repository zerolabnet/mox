export const langPreference = (): LangPreference => {
	try {
		const v = localStorage.getItem(langKey)
		if (v === 'auto' || v === 'en' || v === 'ru') {
			return v
		}
	} catch (err) {
	}
	return 'auto'
}

const browserIsRussian = (): boolean => {
	const list = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || '']
	return list.some(l => l.toLowerCase().startsWith('ru'))
}

export const resolvedLang = (): Lang => {
	const pref = langPreference()
	if (pref === 'ru') {
		return 'ru'
	}
	if (pref === 'en') {
		return 'en'
	}
	return browserIsRussian() ? 'ru' : 'en'
}

export const uiLocale = (): string => resolvedLang() === 'ru' ? 'ru' : 'en'

export const ui = (en: string): string => {
	if (resolvedLang() !== 'ru') {
		return en
	}
	const line = ru[en]
	return line === undefined ? en : line
}

export const unreadTitle = (n: number): string => {
	if (resolvedLang() !== 'ru') {
		return n + ' unread'
	}
	const mod10 = n % 10
	const mod100 = n % 100
	const singular = mod10 === 1 && mod100 !== 11
	return n + (singular ? ' непрочитанное' : ' непрочитанных')
}

export const chooseLang = (pref: LangPreference) => {
	if (pref === langPreference()) {
		return
	}
	try {
		localStorage.setItem(langKey, pref)
	} catch (err) {
	}
	location.reload()
}

export const wroteLine = (when: string, name: string): string => {
	if (resolvedLang() === 'ru') {
		return when + ', ' + name + ' написал(а):\n'
	}
	return 'On ' + when + ', ' + name + ' wrote:\n'
}

export type MailboxNamed = { Name: string, Archive?: boolean, Draft?: boolean, Junk?: boolean, Sent?: boolean, Trash?: boolean }

// Special-use folders get a Russian name. The stored name stays the server name.
// Children keep their own last segment.
export const mailboxLabel = (mb: MailboxNamed, shown?: string): string => {
	const leaf = mb.Name.split('/').pop() || mb.Name
	const text = shown === undefined ? leaf : shown
	if (text !== leaf && text !== mb.Name) {
		return text
	}
	if (resolvedLang() !== 'ru') {
		return text
	}
	if (mb.Trash) {
		return 'Корзина'
	}
	if (mb.Junk) {
		return 'Спам'
	}
	if (mb.Sent) {
		return 'Отправленные'
	}
	if (mb.Draft) {
		return 'Черновики'
	}
	if (mb.Archive) {
		return 'Архив'
	}
	if (leaf === 'Inbox' && mb.Name.split('/')[0] === 'Inbox') {
		return 'Входящие'
	}
	return text
}

